// Renders the launcher icon and splash images into resources/ using a headless
// browser (Playwright), from the same artwork the game uses. Then
// `npx @capacitor/assets generate --android` turns them into Android resources.
// Usage: npm run icons   (needs `npm i -D playwright` once, or a global install)
import { mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';
import { build } from 'esbuild';

// Playwright from the project, or from NODE_PATH if it is installed globally.
const require = createRequire(import.meta.url);
const searchPaths = [process.cwd(), ...(process.env.NODE_PATH || '').split(':').filter(Boolean)];
const { chromium } = require(require.resolve('playwright', { paths: searchPaths }));
mkdirSync('resources', { recursive: true });

// Bundle the logo/Zip artwork so the images match the game exactly.
const art = await build({
  stdin: { contents: "export { logoHTML, zipSVG } from './src/art.js';", resolveDir: resolve('.') },
  bundle: true, format: 'iife', globalName: 'ART', write: false, tsconfig: 'tsconfig.json',
});
const artJs = art.outputFiles[0].text;

const STARS = Array.from({ length: 40 }, (_, i) => {
  const x = (i * 263) % 1000;
  const y = (i * 151 + 37) % 1000;
  const r = 2 + (i % 4);
  return `<circle cx="${x / 10}%" cy="${y / 10}%" r="${r}" fill="#FFE58A" opacity="${0.25 + (i % 3) * 0.2}"/>`;
}).join('');

const iconArt = (withBg) => `
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024">
  ${withBg ? `<rect width="1024" height="1024" fill="#1E1A4D"/>${STARS}` : ''}
  <g id="mark">
    <path d="M222 742 L470 404 L770 650" fill="none" stroke="#FFE58A" stroke-width="86" stroke-linecap="round" stroke-linejoin="round" opacity=".3"/>
    <path d="M222 742 L470 404 L770 650" fill="none" stroke="#FFE58A" stroke-width="30" stroke-linecap="round" stroke-linejoin="round"/>
    ${[[222, 742, '1', '#FFC93C'], [470, 404, '2', '#FFC93C'], [770, 650, '3', '#3EE0B0']].map(([x, y, n, f]) => `
      <circle cx="${x}" cy="${y}" r="86" fill="${f}" stroke="#241C5C" stroke-width="16"/>
      <text x="${x}" y="${y + 38}" text-anchor="middle" font-family="Fredoka" font-weight="700" font-size="112" fill="#241C5C">${n}</text>`).join('')}
  </g>
  <g id="zip" transform="translate(600 92)"></g>
</svg>`;

async function render(page, html, out, size, transparent = false) {
  await page.setViewportSize({ width: size, height: size });
  // Written next to style.css so the bundled fonts and styles load.
  const tmp = resolve('www/.render-asset.html');
  writeFileSync(tmp, `<!doctype html><html><head><link rel="stylesheet" href="style.css"><style>
    html,body{margin:0;width:${size}px;height:${size}px;overflow:hidden;background:${transparent ? 'transparent' : '#1E1A4D'}}
    .zip{filter:none} #logo .logo{display:inline-block}
  </style></head><body>${html}<script>${artJs}</script></body></html>`);
  await page.goto(pathToFileURL(tmp).href);
  await page.evaluate(() => {
    const z = document.querySelector('#zip');
    if (z) z.innerHTML = ART.zipSVG({ size: 330 }).replace('<svg ', '<svg x="0" y="0" ');
    const l = document.querySelector('#logo');
    if (l) l.innerHTML = ART.logoHTML();
  });
  await page.evaluate(() => document.fonts.ready);
  await page.waitForTimeout(300);
  await page.screenshot({ path: out, omitBackground: transparent });
  rmSync(tmp);
  console.log('wrote', out);
}

const browser = await chromium.launch();
const page = await browser.newPage();
await render(page, iconArt(true), 'resources/icon-only.png', 1024);
// Adaptive icon: the mark shrunk into the 66% safe zone, on a separate background.
await render(page, `<div style="transform:scale(.62);transform-origin:center">${iconArt(false)}</div>`, 'resources/icon-foreground.png', 1024, true);
await render(page, `<svg viewBox="0 0 1024 1024" width="1024" height="1024"><rect width="1024" height="1024" fill="#1E1A4D"/>${STARS}</svg>`, 'resources/icon-background.png', 1024);
const splash = `<div style="position:relative;width:2732px;height:2732px;background:#1E1A4D">
  <svg viewBox="0 0 2732 2732" width="2732" height="2732" style="position:absolute;inset:0">${STARS.replace(/r="(\d)"/g, (_, r) => `r="${r * 3}"`)}</svg>
  <div id="logo" style="position:absolute;left:0;right:0;top:50%;transform:translateY(-50%);text-align:center;--logo-size:440px"></div></div>`;
await render(page, splash, 'resources/splash.png', 2732);
await render(page, splash, 'resources/splash-dark.png', 2732);
await browser.close();
writeFileSync('resources/README.md', 'Generated by `npm run icons` (scripts/render-assets.mjs). Edit the script, not these PNGs.\n');
