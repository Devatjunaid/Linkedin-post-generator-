package com.devatjunaid.examclock.ui.planner

import androidx.lifecycle.ViewModel
import androidx.lifecycle.viewModelScope
import com.devatjunaid.examclock.AppContainer
import com.devatjunaid.examclock.data.db.ExamEntity
import com.devatjunaid.examclock.data.db.SessionEntity
import com.devatjunaid.examclock.data.db.SessionWithExam
import com.devatjunaid.examclock.domain.SessionType
import com.devatjunaid.examclock.ui.components.Format
import kotlinx.coroutines.ExperimentalCoroutinesApi
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.SharingStarted
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.combine
import kotlinx.coroutines.flow.flatMapLatest
import kotlinx.coroutines.flow.map
import kotlinx.coroutines.flow.stateIn
import kotlinx.coroutines.launch
import java.time.LocalDate
import java.time.LocalTime
import java.time.temporal.TemporalAdjusters
import java.time.temporal.WeekFields
import java.util.Locale

data class PlannerState(
    val loading: Boolean = true,
    val selected: LocalDate = LocalDate.now(),
    val week: List<LocalDate> = emptyList(),
    val byDay: Map<LocalDate, List<SessionWithExam>> = emptyMap(),
    val exams: List<ExamEntity> = emptyList(),
) {
    val selectedSessions: List<SessionWithExam> get() = byDay[selected].orEmpty()
    val plannedMinutes: Int get() = selectedSessions.sumOf { it.session.durationMinutes }
    val doneMinutes: Int get() = selectedSessions.filter { it.session.completed }.sumOf { it.session.durationMinutes }
}

@OptIn(ExperimentalCoroutinesApi::class)
class PlannerViewModel(container: AppContainer) : ViewModel() {
    private val repo = container.repository
    private val selected = MutableStateFlow(LocalDate.now())
    private val firstDay = WeekFields.of(Locale.getDefault()).firstDayOfWeek

    private val weekStart = selected.map { it.with(TemporalAdjusters.previousOrSame(firstDay)) }

    val state: StateFlow<PlannerState> = combine(
        selected,
        weekStart.flatMapLatest { start -> repo.observeSessions(start, start.plusDays(7)).map { start to it } },
        repo.observeExams(),
    ) { day, (start, sessions), exams ->
        PlannerState(
            loading = false,
            selected = day,
            week = (0L until 7L).map { start.plusDays(it) },
            byDay = sessions.groupBy { Format.toLocalDate(it.session.startAt) },
            exams = exams.filter { it.examAt == null || it.examAt > System.currentTimeMillis() },
        )
    }.stateIn(viewModelScope, SharingStarted.WhileSubscribed(5_000), PlannerState())

    fun select(date: LocalDate) {
        selected.value = date
    }

    fun shiftWeek(weeks: Long) {
        selected.value = selected.value.plusWeeks(weeks)
    }

    fun today() {
        selected.value = LocalDate.now()
    }

    fun setCompleted(item: SessionWithExam, completed: Boolean) = viewModelScope.launch {
        repo.setSessionCompleted(item.session, completed)
    }

    fun delete(item: SessionWithExam) = viewModelScope.launch { repo.deleteSession(item.session) }

    fun add(examId: Long?, title: String, type: SessionType, date: LocalDate, time: LocalTime, minutes: Int) = viewModelScope.launch {
        repo.addSession(
            SessionEntity(
                examId = examId,
                topicId = null,
                title = title.trim(),
                type = type.code,
                startAt = Format.millis(date, time),
                durationMinutes = minutes,
                completed = false,
                autoGenerated = false,
            ),
        )
    }
}
