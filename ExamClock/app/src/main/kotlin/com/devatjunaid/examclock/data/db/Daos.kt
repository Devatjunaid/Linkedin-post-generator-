package com.devatjunaid.examclock.data.db

import androidx.room.Dao
import androidx.room.Delete
import androidx.room.Insert
import androidx.room.Query
import androidx.room.Transaction
import androidx.room.Update
import kotlinx.coroutines.flow.Flow

@Dao
interface ExamDao {
    @Query("SELECT * FROM exams ORDER BY examAt IS NULL, examAt, title")
    fun observeAll(): Flow<List<ExamEntity>>

    @Query("SELECT * FROM exams WHERE id = :id")
    fun observe(id: Long): Flow<ExamEntity?>

    @Query("SELECT * FROM exams WHERE id = :id")
    suspend fun get(id: Long): ExamEntity?

    @Query("SELECT * FROM exams WHERE examAt IS NOT NULL AND examAt > :now ORDER BY examAt")
    suspend fun upcoming(now: Long): List<ExamEntity>

    @Query("SELECT COUNT(*) FROM exams")
    suspend fun count(): Int

    @Insert
    suspend fun insert(exam: ExamEntity): Long

    @Update
    suspend fun update(exam: ExamEntity)

    @Delete
    suspend fun delete(exam: ExamEntity)
}

@Dao
interface TopicDao {
