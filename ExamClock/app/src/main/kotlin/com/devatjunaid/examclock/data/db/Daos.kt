}

@Dao
abstract class SessionDao {
    @Query(
        """
        SELECT s.*, e.title AS examTitle, e.colorIndex AS examColor, t.title AS topicTitle
        FROM sessions s
        LEFT JOIN exams e ON s.examId = e.id
        LEFT JOIN topics t ON s.topicId = t.id
        WHERE s.startAt >= :from AND s.startAt < :to
        ORDER BY s.startAt
        """,
    )
    abstract fun observeBetween(from: Long, to: Long): Flow<List<SessionWithExam>>

    @Query("SELECT * FROM sessions WHERE id = :id")
    abstract suspend fun get(id: Long): SessionEntity?

    @Query("SELECT * FROM sessions WHERE autoGenerated = 0 AND startAt >= :from")
    abstract suspend fun manualFrom(from: Long): List<SessionEntity>

    @Query("SELECT * FROM sessions WHERE completed = 0 AND startAt >= :from AND startAt < :to ORDER BY startAt")
    abstract suspend fun openBetween(from: Long, to: Long): List<SessionEntity>

    @Query("DELETE FROM sessions WHERE autoGenerated = 1 AND completed = 0 AND startAt >= :from")
    abstract suspend fun deleteOpenAutoFrom(from: Long)

    @Insert
    abstract suspend fun insert(session: SessionEntity): Long

    @Insert
    abstract suspend fun insertAll(sessions: List<SessionEntity>)

    @Update
    abstract suspend fun update(session: SessionEntity)

    @Delete
    abstract suspend fun delete(session: SessionEntity)

    @Transaction
    open suspend fun replaceAutoPlan(from: Long, sessions: List<SessionEntity>) {
        deleteOpenAutoFrom(from)
        insertAll(sessions)
    }
}

@Dao
interface StudyLogDao {
    @Query("SELECT * FROM study_logs WHERE startedAt >= :from ORDER BY startedAt")
    fun observeSince(from: Long): Flow<List<StudyLogEntity>>

    @Query("SELECT COALESCE(SUM(minutes), 0) FROM study_logs WHERE sessionId = :sessionId")
    suspend fun minutesForSession(sessionId: Long): Int

    @Query("DELETE FROM study_logs WHERE sessionId = :sessionId AND manual = 1")
    suspend fun deleteManualForSession(sessionId: Long)

    @Insert
    suspend fun insert(log: StudyLogEntity): Long
}
