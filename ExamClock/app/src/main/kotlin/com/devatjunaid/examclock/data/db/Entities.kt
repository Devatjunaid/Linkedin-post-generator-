package com.devatjunaid.examclock.data.db

import androidx.room.ColumnInfo
import androidx.room.Embedded
import androidx.room.Entity
import androidx.room.ForeignKey
import androidx.room.Index
import androidx.room.PrimaryKey

/** One exam paper, e.g. "Physics · Paper I" in the group "FSc Part II". */
@Entity(tableName = "exams")
data class ExamEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val title: String,
    /** Board, series or qualification, e.g. "FBISE HSSC-II" or "JEE Main". */
    val groupName: String,
    /** Start of the exam in epoch millis, or null while the official date is not known yet. */
    val examAt: Long?,
    val durationMinutes: Int,
    val location: String,
    val colorIndex: Int,
    val notes: String,
    val templateId: String?,
    val createdAt: Long,
)

@Entity(
    tableName = "topics",
    foreignKeys = [
        ForeignKey(entity = ExamEntity::class, parentColumns = ["id"], childColumns = ["examId"], onDelete = ForeignKey.CASCADE),
    ],
    indices = [Index("examId")],
)
data class TopicEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val examId: Long,
    val title: String,
    /** [com.devatjunaid.examclock.domain.TopicStatus.code] */
    val status: Int,
    /** 1..5 */
    val confidence: Int,
    val position: Int,
    val updatedAt: Long,
)

@Entity(
    tableName = "sessions",
    foreignKeys = [
        ForeignKey(entity = ExamEntity::class, parentColumns = ["id"], childColumns = ["examId"], onDelete = ForeignKey.CASCADE),
        ForeignKey(entity = TopicEntity::class, parentColumns = ["id"], childColumns = ["topicId"], onDelete = ForeignKey.SET_NULL),
    ],
    indices = [Index("examId"), Index("topicId"), Index("startAt")],
)
data class SessionEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val examId: Long?,
    val topicId: Long?,
    val title: String,
    /** [com.devatjunaid.examclock.domain.SessionType.code] */
    val type: Int,
    val startAt: Long,
    val durationMinutes: Int,
    val completed: Boolean,
    val autoGenerated: Boolean,
)

/** Minutes actually studied (from the focus timer or a session ticked off by hand). */
@Entity(
    tableName = "study_logs",
    foreignKeys = [
        ForeignKey(entity = ExamEntity::class, parentColumns = ["id"], childColumns = ["examId"], onDelete = ForeignKey.SET_NULL),
        ForeignKey(entity = SessionEntity::class, parentColumns = ["id"], childColumns = ["sessionId"], onDelete = ForeignKey.SET_NULL),
    ],
    indices = [Index("examId"), Index("sessionId"), Index("startedAt")],
)
data class StudyLogEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val examId: Long?,
    val sessionId: Long?,
    val startedAt: Long,
    val minutes: Int,
    /** True when added by ticking a session off by hand (removed again when unticked). */
    val manual: Boolean = false,
)

data class SessionWithExam(
    @Embedded val session: SessionEntity,
    @ColumnInfo(name = "examTitle") val examTitle: String?,
    @ColumnInfo(name = "examColor") val examColor: Int?,
    @ColumnInfo(name = "topicTitle") val topicTitle: String?,
)
